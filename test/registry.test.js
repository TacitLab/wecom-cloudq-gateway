"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
process.env.ADMIN_PASSWORD = "test-admin-password";
process.env.SQLITE_PATH = ":memory:";
const { db } = require("../src/database");
const registry = require("../src/registry");
const store = require("../src/store");
test.beforeEach(() => db().exec("DELETE FROM wma_tasks; DELETE FROM wma_conversations; DELETE FROM alert_integrations; DELETE FROM wecom_bots; DELETE FROM wma_agents; DELETE FROM wma_credentials; DELETE FROM tencent_credentials;"));
const credential = (name = "WMA") => registry.saveWmaCredential({ name, secretId: "AKID_test_value", secretKey: "wma-secret" });
const agent = (key, id = "01M74MGWSA4B9N2AHP4NVS50RX") => registry.saveAgent({ name: "SRE", credentialConfigId: key.id, agentId: id });
test("AK/SK credentials and Agent public state never expose secrets", () => {
  assert.throws(() => registry.saveWmaCredential({ name: "Missing" }), /SecretId.*required/);
  assert.throws(() => registry.saveWmaCredential({ name: "Missing", secretId: "AKID_test" }), /SecretKey.*required/);
  const key = credential(); const a = agent(key);
  assert.equal(key.region, "ap-guangzhou");
  assert.equal(key.secretKeyConfigured, true);
  assert.doesNotMatch(JSON.stringify([registry.listWmaCredentials(), registry.listAgents()]), /AKID_test_value|wma-secret/);
  assert.equal(registry.getWmaCredential(key.id, { secrets: true }).secretKey, "wma-secret");
  assert.equal(registry.getAgent(a.id, { secrets: true }).secretId, "AKID_test_value");
  assert.equal(registry.getAgent(a.id).credentialName, key.name);
});
test("AK/SK and region rotation invalidates all linked session namespaces", () => {
  const key = credential(); const first = agent(key); const second = agent(key, "01SECOND");
  registry.saveWmaCredential({ name: "Renamed", secretId: "", secretKey: "" }, key.id);
  assert.equal(registry.getAgent(first.id).revision, first.revision);
  registry.saveWmaCredential({ name: "Rotated", secretKey: "secret2" }, key.id);
  for (const a of [first, second]) assert.equal(registry.getAgent(a.id).revision, a.revision + 1);
  assert.equal(registry.getAgent(first.id, { secrets: true }).secretId, "AKID_test_value");
  assert.equal(registry.getAgent(first.id, { secrets: true }).secretKey, "secret2");
  registry.saveWmaCredential({ name: "Region", region: "ap-beijing" }, key.id);
  assert.equal(registry.getAgent(first.id).revision, first.revision + 2);
  assert.equal(registry.getAgent(first.id).region, "ap-beijing");
  assert.throws(() => registry.deleteWmaCredential(key.id), /still used/);
});
test("Agent selection requires credential references and scopes duplicates by identity", () => {
  const first = credential("one"); const second = credential("two"); const a = agent(first);
  assert.throws(() => registry.saveAgent({ agentId: a.agentId }), /credential configuration.*required/);
  assert.throws(() => agent(first), /already added/);
  assert.equal(registry.findAgentByBusinessId(a.agentId, first.id).id, a.id);
  assert.equal(registry.findAgentByBusinessId(a.agentId, second.id), undefined);
  assert.doesNotThrow(() => agent(second));
  assert.throws(() => registry.saveAgent({ agentId: "../wrong", credentialConfigId: first.id }), /Invalid WMA Agent ID/);
});
test("Bot pairing reuses Agents and protects referenced configurations", () => {
  const key = credential(); const first = agent(key); const second = agent(key, "01SECOND");
  const bot = registry.saveBot({ name: "Bot", botId: "bot-1", secret: "bot-secret", agentConfigId: first.id });
  assert.equal(registry.pairForBot(bot.id).agent.secretKey, "wma-secret");
  assert.equal(registry.listBots()[0].secret, undefined);
  assert.throws(() => registry.deleteAgent(first.id), /still paired/);
  registry.saveBot({ ...bot, secret: "", agentConfigId: second.id, showThinking: false }, bot.id);
  assert.equal(registry.getBot(bot.id).agentConfigId, second.id);
  assert.equal(registry.getBot(bot.id, { secrets: true }).secret, "bot-secret");
  assert.equal(registry.getBot(bot.id).showThinking, false);
});
test("session reset clears WMA mappings and task redaction removes private messages", () => {
  const a = agent(credential());
  store.setConversation("conversation", { botConfigId: "bot", agentConfigId: a.id, agentRevision: a.revision }, { sessionId: "session" });
  assert.equal(registry.resetAgentSessions(a.id).cleared, 1);
  assert.equal(store.conversation("conversation"), undefined);
  assert.equal(registry.getAgent(a.id).revision, a.revision + 1);
  const { task } = store.enqueueTask({ botConfigId: "bot", agentConfigId: a.id, conversationKey: "conversation", externalMsgId: "message", frame: { secret: "private" }, command: "message", content: "sensitive" });
  store.redactTask(task.id);
  assert.deepEqual({ ...db().prepare("SELECT content,frame_json FROM wma_tasks WHERE id=?").get(task.id) }, { content: "", frame_json: "{}" });
});
test("monitoring credentials stay independent of WMA credentials", () => {
  const c = registry.saveTencentCredential({ name: "Monitor", secretId: "AKID_monitor", secretKey: "monitor-secret" });
  assert.equal(registry.getTencentCredential(c.id).secretKey, undefined);
  assert.equal(registry.listWmaCredentials().length, 0);
  registry.saveTencentCredential({ name: "Renamed", secretId: "", secretKey: "" }, c.id);
  assert.equal(registry.getTencentCredential(c.id, { secrets: true }).secretKey, "monitor-secret");
});
